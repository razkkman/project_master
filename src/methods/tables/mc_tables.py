def build_table_arrays(A: float = 1.0) -> Tuple[np.ndarray, np.ndarray]:
    """
    Создает одномерные массивы площади и объема размером 256
    для мгновенной векторизованной индексации по 8-битному коду куба.
    """
    raw = get_lookup_table_raw(A)
    table_s = np.zeros(256, dtype=np.float64)
    table_v = np.zeros(256, dtype=np.float64)

    for k, (s, v) in raw.items():
        idx = int(k, 2)
        table_s[idx] = s
        table_v[idx] = v

    return table_s, table_v


