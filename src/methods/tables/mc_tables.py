def build_correction_matrices() -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Строит 16x16 матрицы коэффициентов поправок на стыках ячеек.
    Строка матрицы соответствует 4-битному индексу грани следующего куба (next),
    столбец - 4-битному индексу грани текущего куба (now).
    """
    def _extract(func, idx_next, idx_now):
        M = np.zeros((16, 16), dtype=np.float64)
        for i in range(16):
            b_next = format(i, '04b')
            anext = ['0'] * 8
            for k, bit in zip(idx_next, b_next):
                anext[k] = bit
            str_next = ''.join(anext)
            for j in range(16):
                b_now = format(j, '04b')
                anow = ['0'] * 8
                for k, bit in zip(idx_now, b_now):
                    anow[k] = bit
                str_now = ''.join(anow)
                M[i, j] = func(str_next, str_now, 1.0)
        return M

    m0 = _extract(Chastnie_Sluchai_, [0, 3, 4, 7], [1, 2, 5, 6])
    m1 = _extract(Chastnie_Sluchai_1_, [0, 1, 4, 5], [2, 3, 6, 7])
    m2 = _extract(Chastnie_Sluchai_2_, [0, 1, 2, 3], [4, 5, 6, 7])
    return m0, m1, m2


